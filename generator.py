#!/usr/bin/env python3
"""
generator.py - Markdown Report Generator for Project Health Monitoring.
Reads raw_data.json and formats a clean daily health status report in daily_report.md.
Uses strictly Python standard library modules (json, os, sys, datetime).
"""

import json
import os
import sys
from datetime import datetime, timezone

RAW_DATA_FILE = os.path.join(os.path.dirname(__file__), "raw_data.json")
REPORT_FILE = os.path.join(os.path.dirname(__file__), "daily_report.md")


def load_raw_data(filepath: str) -> dict:
    if not os.path.exists(filepath):
        sys.exit(f"Error: Raw data file not found at '{filepath}'. Run fetcher.js first.")
    
    with open(filepath, "r", encoding="utf-8") as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as exc:
            sys.exit(f"Error: Malformed JSON in '{filepath}': {exc}")


def generate_markdown(data: dict) -> str:
    now_utc = datetime.now(timezone.utc)
    date_str = now_utc.strftime("%Y-%m-%d")
    timestamp_str = now_utc.strftime("%Y-%m-%d %H:%M:%S UTC")

    results = data.get("results", [])
    total = len(results)
    healthy = sum(1 for r in results if r.get("isHealthy"))
    unhealthy = total - healthy
    
    avg_response_time = (
        round(sum(r.get("responseTimeMs", 0) for r in results) / total)
        if total > 0
        else 0
    )

    all_operational = (unhealthy == 0 and total > 0)
    system_status_badge = "🟢 **All Systems Operational**" if all_operational else "🔴 **Degraded Performance / Failures Detected**"

    lines = [
        f"# 📊 Centralized Project Health Report",
        "",
        f"> **Generated Date:** {date_str}  ",
        f"> **Last Run Time:** `{timestamp_str}`  ",
        f"> **Overall System Status:** {system_status_badge}",
        "",
        "## 📈 Executive Summary",
        "",
        "| Metric | Value |",
        "| :--- | :--- |",
        f"| **Total Monitored Endpoints** | `{total}` |",
        f"| **Operational Endpoints (✅)** | `{healthy}` |",
        f"| **Failed / Degraded (❌)** | `{unhealthy}` |",
        f"| **Average Latency** | `{avg_response_time} ms` |",
        "",
        "## 🔍 Detailed Health Checks",
        "",
        "| Status | Project Name | Type | Target URL | HTTP Code | Latency | Last Checked (UTC) |",
        "| :---: | :--- | :---: | :--- | :---: | :---: | :--- |"
    ]

    for item in results:
        status_icon = "✅" if item.get("isHealthy") else "❌"
        name = item.get("name", "Unknown")
        item_type = item.get("type", "generic").upper()
        url = item.get("url", "#")
        http_status = item.get("status", "N/A")
        status_text = item.get("statusText", "")
        code_display = f"`{http_status}`" if http_status else "`ERR`"
        latency = f"`{item.get('responseTimeMs', 0)} ms`"
        checked_at = item.get("timestamp", "").replace("T", " ")[:19]

        lines.append(
            f"| {status_icon} | **{name}** | `{item_type}` | [{url}]({url}) | {code_display} {status_text} | {latency} | `{checked_at}` |"
        )

    # Detailed Incident / Error log if any endpoints failed
    failing_items = [r for r in results if not r.get("isHealthy")]
    if failing_items:
        lines.extend([
            "",
            "## ⚠️ Active Incidents & Failures",
            ""
        ])
        for fail in failing_items:
            error_reason = fail.get("error") or fail.get("statusText") or f"HTTP {fail.get('status')}"
            lines.extend([
                f"- **{fail.get('name')}** (`{fail.get('url')}`)",
                f"  - **Status Code:** `{fail.get('status')}`",
                f"  - **Issue Detail:** `{error_reason}`",
                ""
            ])

    lines.extend([
        "---",
        "*Automated report generated by GitHub Actions polyglot workflow (Node.js Fetcher + Python Report Generator).*"
    ])

    return "\n".join(lines) + "\n"


def main():
    print("[Generator] Loading raw metrics from raw_data.json...")
    data = load_raw_data(RAW_DATA_FILE)

    print("[Generator] Compiling daily health report markdown...")
    report_content = generate_markdown(data)

    with open(REPORT_FILE, "w", encoding="utf-8") as f:
        f.write(report_content)

    print(f"[Generator] Successfully wrote daily health report to '{REPORT_FILE}'")


if __name__ == "__main__":
    main()
